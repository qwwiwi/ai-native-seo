// Per-guide cover banner (neo-noir EdgeLab Space style, scene + tool logo + title).
// A guide gets a hero cover when site/covers/<slug>.png exists (generated by the
// edgelab-covers skill). Auto-wired by file presence — no manual list to maintain.
const COVERS_DIR = join(ROOT, "site", "covers");
function coverFor(slug) {
  // Prefer WebP (≈14× smaller than the PNG — see the perf pass); fall back to PNG.
  // content-hash query → each cover update is a new URL = instant cache-bust on
  // Cloudflare + browsers (covers are at a FIXED path, unlike hashed CSS/JS).
  for (const ext of ["webp", "png"]) {
    const p = join(COVERS_DIR, `${slug}.${ext}`);
    if (existsSync(p)) {
      const v = createHash("sha256").update(readFileSync(p)).digest("hex").slice(0, 10);
      return `/covers/${slug}.${ext}?v=${v}`;
    }
  }
  return "";
}
