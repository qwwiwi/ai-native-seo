function mdToHtml(md, opts = {}) {
  const allowImages = !!opts.allowImages; // articles embed any images; guides are text-only…
  // …EXCEPT in-body diagrams/block-schemes (site/images/diagrams/*) — those render in BOTH
  // articles and guides (prince 2026-06-17). Strip every other image for guides.
  if (!allowImages) md = md.replace(/!\[[^\]]*\]\((?!\/images\/diagrams\/)[^)]*\)/g, "");
  md = md.replace(/<img[^>]*>/gi, "");
  md = md.replace(/<figure[\s\S]*?<\/figure>/gi, "");

  const lines = md.split("\n");
  const out = [];
  let i = 0;
  const headings = []; // collected ## for TOC

  while (i < lines.length) {
    let line = lines[i];

    // fenced code block ```lang
    const fence = line.match(/^```(\w*)\s*$/);
    if (fence) {
      i++;
      const buf = [];
      while (i < lines.length && !/^```\s*$/.test(lines[i])) {
        buf.push(lines[i]);
        i++;
      }
      i++; // closing ```
      out.push(
        `<div class="code-block"><button class="copy-btn" type="button" data-copy="code" aria-label="Скопировать код">${COPY_ICON_SVG}</button><pre class="gp-code"><code>${esc(buf.join("\n"))}</code></pre></div>`,
      );
      continue;
    }

    // directive ::: name [title]
    const dir = line.match(/^:::(\w+)(?:\s+(.*))?$/);
    if (dir && dir[1] !== "") {
      const name = dir[1];
      const title = (dir[2] || "").trim();
      i++;
      const buf = [];
      while (i < lines.length && !/^:::\s*$/.test(lines[i])) {
        buf.push(lines[i]);
        i++;
      }
      i++; // closing :::
      // video clip embed: `:::kinescope <video_id>` + caption lines → responsive 16:9 player.
      // Works in articles AND guides (deliberate embed, not a decorative image). Canonical way to
      // put an эфир cut / any Kinescope video into body copy.
      if (name === "kinescope") {
        const vid = (dir[2] || "").trim();
        const safeVid = /^[A-Za-z0-9_-]+$/.test(vid) ? vid : "";
        const cap = inline(buf.join(" ").trim());
        if (safeVid) {
          out.push(
            `<figure class="gp-video"><div class="kinescope-embed"><iframe src="https://kinescope.io/embed/${safeVid}" allow="autoplay; fullscreen; picture-in-picture; encrypted-media; clipboard-write; gyroscope; accelerometer" frameborder="0" allowfullscreen loading="lazy"></iframe></div>${cap ? `<figcaption>${cap}</figcaption>` : ""}</figure>`,
          );
        }
        continue;
      }
      const label = DIRECTIVE_LABEL[name] || name.toUpperCase();
      const inner = mdToHtml(buf.join("\n")).html;
      const head = title ? `${label} · ${inline(title)}` : label;
      const copyBtn =
        name === "prompt"
          ? `<button class="copy-btn" type="button" data-copy="prompt" aria-label="Скопировать промпт">${COPY_ICON_SVG}</button>`
          : "";
      out.push(
        `<div class="blk-callout dir-${esc(name)}">${copyBtn}<span class="gp-eyebrow"><span class="dot"></span>${head}</span>${inner}</div>`,
      );
      continue;
    }

    // table (only viral-reels): header row | --- | rows
    if (/^\|/.test(line) && i + 1 < lines.length && /^\|[\s:|-]+\|?\s*$/.test(lines[i + 1])) {
      const header = splitRow(line);
      i += 2; // skip header + separator
      const rows = [];
      while (i < lines.length && /^\|/.test(lines[i])) {
        rows.push(splitRow(lines[i]));
        i++;
      }
      let html = '<table class="gp-table"><thead><tr>';
      html += header.map((h) => `<th>${inline(h)}</th>`).join("");
      html += "</tr></thead><tbody>";
      for (const r of rows) {
        html += "<tr>" + r.map((c) => `<td>${inline(c)}</td>`).join("") + "</tr>";
      }
      html += "</tbody></table>";
      out.push(html);
      continue;
    }

    // markdown image: ![alt](src) on its own line → figure. Articles allow any image;
    // guides allow ONLY diagrams (/images/diagrams/*) — see the strip rule above.
    const imgm = line.match(/^!\[([^\]]*)\]\(([^)\s]+)\)\s*$/);
    if (imgm && (allowImages || /^\/images\/diagrams\//.test(imgm[2]))) {
      const alt = esc(imgm[1]);
      const src = esc(imgm[2]);
      out.push(`<figure class="gp-fig"><img src="${src}" alt="${alt}" loading="lazy">${alt ? `<figcaption>${alt}</figcaption>` : ""}</figure>`);
      i++;
      continue;
    }

    // headings
    const h = line.match(/^(#{1,4})\s+(.*)$/);
    if (h) {
      const level = h[1].length;
      const text = h[2].trim();
      // The MDX body's leading "# Title" duplicates the article H1 — drop it.
      if (level === 1) { i++; continue; }
      // index-based id on each H2 so the TOC can anchor + scroll-spy to it (sec-N
      // matches the Nth entry of the headings/toc array, in order).
      if (level === 2) {
        out.push(`<h2 id="sec-${headings.length}">${inline(text)}</h2>`);
        headings.push(text);
        i++;
        continue;
      }
      out.push(`<h${level}>${inline(text)}</h${level}>`);
      i++;
      continue;
    }

    // unordered list
    if (/^\s*[-*]\s+/.test(line)) {
      const buf = [];
      while (i < lines.length && /^\s*[-*]\s+/.test(lines[i])) {
        buf.push(lines[i].replace(/^\s*[-*]\s+/, ""));
        i++;
      }
      out.push("<ul>" + buf.map((b) => `<li>${inline(b)}</li>`).join("") + "</ul>");
      continue;
    }

    // ordered list
    if (/^\s*\d+\.\s+/.test(line)) {
      const buf = [];
      while (i < lines.length && /^\s*\d+\.\s+/.test(lines[i])) {
        buf.push(lines[i].replace(/^\s*\d+\.\s+/, ""));
        i++;
      }
      out.push("<ol>" + buf.map((b) => `<li>${inline(b)}</li>`).join("") + "</ol>");
      continue;
    }

    // blank
    if (line.trim() === "") { i++; continue; }

    // paragraph: gather until blank / block start
    const buf = [line];
    i++;
    while (
      i < lines.length &&
      lines[i].trim() !== "" &&
      !/^(#{1,4}\s|```|:::|\s*[-*]\s|\s*\d+\.\s|\|)/.test(lines[i])
    ) {
      buf.push(lines[i]);
      i++;
    }
    out.push(`<p>${inline(buf.join(" "))}</p>`);
  }

  return { html: out.join("\n"), headings };
}
function splitRow(line) {
  return line
    .replace(/^\||\|$/g, "")
    .split("|")
    .map((s) => s.trim());
}

// Build the full-text search field `st`: a single lowercased plain-text blob of
// title + desc + tldr + tags + the body (HTML tags stripped, whitespace collapsed,
// capped) — consumed by MiniSearch in gf-app.jsx. Cap keeps guides-data.js lean.
function buildSearchText({ title, desc, tldr, tags, bodyHtml }) {
  const bodyText = String(bodyHtml || "")
    .replace(/<[^>]*>/g, " ") // strip tags
    .replace(/&[a-z]+;|&#\d+;/gi, " ") // drop HTML entities (&amp; &lt; …)
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 2500); // cap to keep the index field small
  return [title, desc, tldr, (tags || []).join(" "), bodyText]
    .filter(Boolean)
    .join(" ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

// «Похожие материалы» per guide for the in-page recirculation block. Relevance =
// same-category boost + INVERSE-FREQUENCY tag overlap (a rare tag like «mcp»/«memory»
// weighs more than the ubiquitous «claude-code»), so links are specific rather than
// «everything relates to everything». Build-time → desktop, mobile and prerender all
// read the same `g.related` slug list. Recency fallback keeps the block ≥3 even for the
// tiny categories (codex/hermes). Stubs are excluded as candidates. Mutates each guide.
function computeRelated(guides, limit = 4) {
  const df = {}; // document frequency per tag
  for (const g of guides) for (const t of g.tags || []) df[t] = (df[t] || 0) + 1;
  const tagW = (t) => 1 / Math.log2(2 + (df[t] || 0)); // rarer tag → bigger weight
  for (const g of guides) {
    if (g.stub) { g.related = []; continue; } // «coming soon» stubs get no related block
    const cand = guides
      .filter((o) => o.slug !== g.slug && !o.stub)
      .map((o) => {
        const shared = (o.tags || []).filter((t) => (g.tags || []).includes(t));
        const score = (o.cat === g.cat ? 3 : 0) + shared.reduce((s, t) => s + tagW(t), 0);
        return { slug: o.slug, score, when: o.updatedAt || o.publishedAt || "" };
      })
      .sort((a, b) => b.score - a.score || b.when.localeCompare(a.when) || a.slug.localeCompare(b.slug));
    const picks = cand.filter((c) => c.score > 0).slice(0, limit).map((c) => c.slug);
    if (picks.length < 3) {
      for (const c of cand) {
        if (picks.length >= limit) break;
        if (!picks.includes(c.slug)) picks.push(c.slug);
      }
    }
    g.related = picks.slice(0, limit);
  }
}

function fmtDate(iso) {
  const months = [
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
  ];
  const d = new Date(iso);
  return `${d.getUTCDate()} ${months[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}

async function main() {
  const files = (await fs.readdir(SRC)).filter((f) => f.endsWith(".mdx")).sort();
  const guides = [];
  let id = 0;
  for (const file of files) {
    const raw = await fs.readFile(join(SRC, file), "utf8");
    const { data, body } = parseFrontmatter(raw);
    const slug = data.slug;
    const cat = SLUG_CAT[slug] || "claude";
    const catName = CAT_NAMES[cat];
    const { html, headings } = mdToHtml(body, { allowImages: data.type === "article" });

    const updated = data.updated_at || data.published_at;
    const published = data.published_at || data.updated_at;
    const guide = {
      id: id++,
      slug,
      cat,
      catName,
      // content type: «guide» (technical, step-by-step, code/prompts) or «article»
      // (readable, narrative, no code — different home section + readable layout).
      type: data.type === "article" ? "article" : "guide",
      cover: coverFor(slug),
      title: data.title,
      desc: data.description || "",
      tldr: data.summary || "",
      tested: `Протестировано · ${fmtDate(updated)}`,
      meta: `ОБНОВЛЕНО ${fmtDate(updated).toUpperCase()} · ${data.estimated_time || ""} МИН ЧТЕНИЯ`,
      level: LEVEL[data.difficulty] || "Новичок",
      min: Number(data.estimated_time) || 10,
      // raw ISO dates + tags — consumed by scripts/build-seo.mjs (JSON-LD, sitemap).
      publishedAt: published || "",
      updatedAt: updated || "",
      // «скоро» placeholder → demoted in the catalog's date/time sorts (sortGuides).
      stub: data.stub === true || data.stub === "true",
      // featured → pinned as the big lead block at the top of the home «Статьи» section.
      featured: data.featured === true || data.featured === "true",
      tags: Array.isArray(data.tags) ? data.tags : [],
      // steps = what_you_need (the design's StepsGuide list)
      steps: Array.isArray(data.what_you_need)
        ? data.what_you_need.map((w) => ({ t: w, d: "" }))
        : [],
      outcome: data.outcome || "",
      toc: headings,
      bodyHtml: html,
    };
    // Full-text search field for MiniSearch (title+desc+tldr+tags+stripped body).
    guide.st = buildSearchText({
      title: guide.title,
      desc: guide.desc,
      tldr: guide.tldr,
      tags: guide.tags,
      bodyHtml: guide.bodyHtml,
    });
    guides.push(guide);
  }

  // «Похожие материалы» — needs the full array (cross-references), so a second pass.
  computeRelated(guides);

  // Sort catalog newest-first by id is arbitrary; keep file order (date-ish).
  const banner =
    "/* AUTO-GENERATED by scripts/build-guides-data.mjs — do not edit by hand.\n" +
    "   Real EdgeLab guide content (text only, no images) for the 1:1 portal design. */\n";
  const js =
    banner +
    "window.__GF_GUIDES = " + JSON.stringify(guides) + ";\n" +
    "window.__GF_GUIDE_BY_SLUG = (function(){var m={};window.__GF_GUIDES.forEach(function(g){m[g.slug]=g;});return m;})();\n";

  await fs.writeFile(OUT, js, "utf8");
  console.log(`Wrote ${guides.length} guides → site/guides-data.js (${(js.length / 1024).toFixed(1)} KB)`);
  for (const g of guides) {
    console.log(`  ${g.slug.padEnd(28)} cat=${g.cat.padEnd(7)} toc=${g.toc.length} steps=${g.steps.length} body=${g.bodyHtml.length}b`);
  }

  // ---- generate one thin wrapper page per guide: site/guides/<slug>.html ----
  // Assets resolve from the parent dir (../). __GF_BASE makes nav/asset hrefs in
  // gf-app.jsx point one level up; __GF_VIEW=guide + __GF_SLUG select the guide.
  const guidesDir = join(ROOT, "site", "guides");
  await fs.mkdir(guidesDir, { recursive: true });
  for (const g of guides) {
    const html = guidePageHtml(g);
    await fs.writeFile(join(guidesDir, `${g.slug}.html`), html, "utf8");
  }
  console.log(`Wrote ${guides.length} per-guide wrappers → site/guides/<slug>.html`);
}

