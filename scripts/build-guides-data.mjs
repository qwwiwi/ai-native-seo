// ---- tiny YAML frontmatter parser (only what these files use) --------------
function parseFrontmatter(raw) {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return { data: {}, body: raw };
  const body = raw.slice(m[0].length);
  const data = {};
  const lines = m[1].split("\n");
  let key = null;
  let list = null;
  for (const line of lines) {
    if (/^\s*-\s+/.test(line) && key) {
      (list = list || []).push(stripQuotes(line.replace(/^\s*-\s+/, "").trim()));
      data[key] = list;
      continue;
    }
    const kv = line.match(/^([a-zA-Z0-9_]+):\s*(.*)$/);
    if (kv) {
      key = kv[1];
      list = null;
      const val = kv[2].trim();
      if (val === "") {
        data[key] = ""; // could be a list header; the next -lines fill it
      } else {
        data[key] = stripQuotes(val);
      }
    }
  }
  return { data, body };
}
function stripQuotes(s) {
  return s.replace(/^["']/, "").replace(/["']$/, "");
}

// ---- markdown → HTML (no deps; covers the constructs in these files) --------
function esc(s) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}
// inline: escape first, then re-introduce only our allowed inline markup.
function inline(text) {
  let t = esc(text);
  // inline code `…`
  t = t.replace(/`([^`]+)`/g, (_, c) => `<code>${c}</code>`);
  // bold **…**
  t = t.replace(/\*\*([^*]+)\*\*/g, (_, c) => `<b>${c}</b>`);
  // markdown links [text](url) → <a>. Internal (/…) stay same-tab, external (http) new-tab.
  // Runs before the bare-URL rule so the link's own URL isn't double-wrapped.
  t = t.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, txt, url) => {
    const ext = /^https?:\/\//.test(url);
    return `<a href="${url}"${ext ? ' target="_blank" rel="noopener"' : ""}>${txt}</a>`;
  });
  // bare URLs → links (after escape, so & is safe)
  t = t.replace(/(^|[\s(])((?:https?:\/\/)[^\s)<]+)/g, (m0, pre, url) => `${pre}<a href="${url}" target="_blank" rel="noopener">${url}</a>`);
  return t;
}

